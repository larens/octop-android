internal data class CoffeePaymentCheckout(
    val orderId: String?,
    val amount: String?,
    val wechatPayUrl: String,
    val qrCodeUrl: String,
)

/**
 * Find the unpaid checkout generated by the Luckin createOrder tool.
 *
 * Tool output is intentionally collapsed under "thinking", but the checkout is the only
 * actionable result of that turn. Once a real pickup code is present, the payment card must
 * disappear so a stale QR code never outlives the order.
 */
internal fun coffeePaymentFrom(parts: List<Part>): CoffeePaymentCheckout? {
    if (pickupCodeFrom(parts) != null) return null

    var payment: CoffeePaymentCheckout? = null
    for (part in parts) {
        if (part.type != PartType.TOOL_RESULT || !part.errorCode.isNullOrBlank()) continue
        if (!part.name.orEmpty().endsWith("createOrder", ignoreCase = true)) continue
        listOfNotNull(part.output, part.text)
            .firstNotNullOfOrNull(::parseCoffeePayment)
            ?.let { payment = it }
    }
    return payment
}

internal fun parseCoffeePayment(raw: String): CoffeePaymentCheckout? {
    val root = parseJsonElement(raw) ?: return null
    return findCoffeePayment(root)
}

internal fun isAllowedWechatPayUrl(value: String): Boolean = runCatching {
    val uri = URI(value)
    uri.scheme.equals("weixin", ignoreCase = true) &&
        uri.host.equals("wxpay", ignoreCase = true) &&
        uri.path == "/bizpayurl"
}.getOrDefault(false)

internal fun isAllowedCoffeeQrUrl(value: String): Boolean = runCatching {
    val uri = URI(value)
    val host = uri.host.orEmpty().lowercase()
    uri.scheme.equals("https", ignoreCase = true) &&
        (host == "lkcoffee.com" || host.endsWith(".lkcoffee.com")) &&
        uri.path == "/transfer/qrcode"
}.getOrDefault(false)

@Composable
internal fun CoffeePaymentCard(payment: CoffeePaymentCheckout) {
    val context = LocalContext.current
    var qrFailed by remember(payment.qrCodeUrl) { mutableStateOf(false) }
    var openFailed by remember(payment.wechatPayUrl) { mutableStateOf(false) }
    val accent = Color(0xFF078A54)
    val qrRequest = remember(payment.qrCodeUrl, context) {
        ImageRequest.Builder(context)
            .data(payment.qrCodeUrl)
            .memoryCachePolicy(CachePolicy.DISABLED)
            .diskCachePolicy(CachePolicy.DISABLED)
            .build()
    }

    fun openWechat() {
        openFailed = !openWechatPayment(context, payment.wechatPayUrl)
    }

    Surface(
        modifier = Modifier
            .fillMaxWidth()
            .border(1.dp, accent.copy(alpha = 0.24f), RoundedCornerShape(16.dp)),
        shape = RoundedCornerShape(16.dp),
        color = accent.copy(alpha = 0.06f),
    ) {
        Column(
            modifier = Modifier.padding(horizontal = 12.dp, vertical = 11.dp),
            verticalArrangement = Arrangement.spacedBy(9.dp),
        ) {
            Row(
                horizontalArrangement = Arrangement.spacedBy(12.dp),
                verticalAlignment = Alignment.CenterVertically,
            ) {
                Surface(
                    modifier = Modifier.clickable(onClick = ::openWechat),
                    shape = RoundedCornerShape(12.dp),
                    color = Color.White,
                ) {
                    Box(
                        modifier = Modifier.size(108.dp).padding(8.dp),
                        contentAlignment = Alignment.Center,
                    ) {
                        if (qrFailed) {
                            Icon(
                                imageVector = Icons.Filled.QrCode2,
                                contentDescription = null,
                                tint = accent,
                                modifier = Modifier.size(38.dp),
                            )
                        } else {
                            AsyncImage(
                                model = qrRequest,
                                contentDescription = stringResource(R.string.chat_payment_qr_description),
                                contentScale = ContentScale.Fit,
                                onError = { qrFailed = true },
                                modifier = Modifier.size(92.dp),
                            )
                        }
                    }
                }

                Column(
                    modifier = Modifier.weight(1f),
                    verticalArrangement = Arrangement.spacedBy(5.dp),
                ) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Icon(
                            imageVector = Icons.Filled.Wallet,
                            contentDescription = null,
                            tint = accent,
                            modifier = Modifier.size(18.dp),
                        )
                        Spacer(Modifier.width(6.dp))
                        Text(
                            text = stringResource(R.string.chat_payment_title),
                            style = MaterialTheme.typography.titleSmall.copy(
                                fontWeight = FontWeight.SemiBold,
                            ),
                            color = MaterialTheme.colorScheme.onSurface,
                        )
                    }
                    Text(
                        text = stringResource(
                            R.string.chat_payment_amount,
                            formatCoffeePaymentAmount(payment.amount),
                        ),
                        style = MaterialTheme.typography.titleLarge.copy(
                            fontWeight = FontWeight.Bold,
                        ),
                        color = accent,
                    )
                    payment.orderId?.takeIf(String::isNotBlank)?.let { orderId ->
                        Text(
                            text = stringResource(R.string.chat_payment_order, orderId),
                            style = MaterialTheme.typography.labelSmall.copy(
                                fontFamily = FontFamily.Monospace,
                            ),
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                            maxLines = 1,
                            overflow = TextOverflow.Ellipsis,
                        )
                    }
                    Text(
                        text = if (qrFailed) {
                            stringResource(R.string.chat_payment_qr_failed)
                        } else {
                            stringResource(R.string.chat_payment_hint)
                        },
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                }
            }

            Button(
                onClick = ::openWechat,
                modifier = Modifier.fillMaxWidth(),
                shape = RoundedCornerShape(12.dp),
                colors = ButtonDefaults.buttonColors(
                    containerColor = accent,
                    contentColor = Color.White,
                ),
            ) {
                Icon(
                    imageVector = Icons.AutoMirrored.Filled.OpenInNew,
                    contentDescription = null,
                    modifier = Modifier.size(17.dp),
                )
                Spacer(Modifier.width(7.dp))
                Text(stringResource(R.string.chat_payment_open_wechat))
            }

            if (openFailed) {
                Text(
                    text = stringResource(R.string.chat_payment_open_failed),
                    style = MaterialTheme.typography.labelSmall,
                    color = MaterialTheme.colorScheme.error,
                )
            }
            Text(
                text = stringResource(R.string.chat_payment_security_hint),
                style = MaterialTheme.typography.labelSmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
        }
    }
}

private fun openWechatPayment(context: Context, url: String): Boolean {
    if (!isAllowedWechatPayUrl(url)) return false
    return try {
        context.startActivity(Intent(Intent.ACTION_VIEW, Uri.parse(url)))
        true
    } catch (_: ActivityNotFoundException) {
        false
    } catch (_: SecurityException) {
        false
    }
}

private fun formatCoffeePaymentAmount(raw: String?): String {
    val value = raw?.trim().orEmpty()
    if (value.isBlank()) return "¥--"
    return if (value.startsWith("¥")) value else "¥$value"
}

private fun findCoffeePayment(element: JsonElement?): CoffeePaymentCheckout? = when (element) {
    is JsonObject -> {
        val needPay = (element["needPay"] ?: element["need_pay"])
            ?.let { it as? JsonPrimitive }
            ?.contentOrNull
            ?.equals("true", ignoreCase = true) == true
        val wechatPayUrl = element.stringValue("payOrderUrl", "pay_order_url")
        val qrCodeUrl = element.stringValue("payOrderQrCodeUrl", "pay_order_qr_code_url")
        if (needPay && isAllowedWechatPayUrl(wechatPayUrl.orEmpty()) &&
            isAllowedCoffeeQrUrl(qrCodeUrl.orEmpty())
        ) {
            CoffeePaymentCheckout(
                orderId = element.stringValue("orderId", "order_id", "orderIdStr", "order_id_str"),
                amount = element.stringValue("discountPrice", "discount_price", "payAmount"),
                wechatPayUrl = requireNotNull(wechatPayUrl),
                qrCodeUrl = requireNotNull(qrCodeUrl),
            )
        } else {
            element.values.firstNotNullOfOrNull(::findCoffeePayment)
        }
    }

    is JsonArray -> element.firstNotNullOfOrNull(::findCoffeePayment)

    is JsonPrimitive -> {
        val text = element.contentOrNull?.trim().orEmpty()
        if (text.startsWith("{") || text.startsWith("[")) {
            findCoffeePayment(parseJsonElement(text))
        } else {
            null
        }
    }

    else -> null
}

private fun JsonObject.stringValue(vararg keys: String): String? =
    keys.firstNotNullOfOrNull { key ->
        (this[key] as? JsonPrimitive)?.contentOrNull?.trim()?.takeIf(String::isNotBlank)
    }

private fun parseJsonElement(raw: String): JsonElement? {
    val text = raw.trim()
    if (text.isEmpty()) return null
    val parsed = runCatching { Json.parseToJsonElement(text) }.getOrNull() ?: return null
    val nested = (parsed as? JsonPrimitive)?.contentOrNull?.trim()
    return if (!nested.isNullOrBlank() && nested != text &&
        (nested.startsWith("{") || nested.startsWith("["))
    ) {
        runCatching { Json.parseToJsonElement(nested) }.getOrNull()
    } else {
        parsed
    }
}
